"""Original procedural studio-light reflection map; no UI imagery is baked in."""
from pathlib import Path
import math,struct,zlib
size=128

def box(x,y,cx,cy,w,h,soft):
    dx=max(abs(x-cx)-w/2,0);dy=max(abs(y-cy)-h/2,0)
    return math.exp(-(dx*dx+dy*dy)/(soft*soft))
rows=[]
for y in range(size):
    row=bytearray()
    for x in range(size):
        u=x/(size-1);v=y/(size-1)
        white=box(u,v,.52,.78,.70,.040,.006)
        white+=box(u,v,.17,.54,.045,.48,.006)*.45
        white+=box(u,v,.53,.70,.64,.008,.004)*.60
        white+=box(u,v,.13,.54,.008,.43,.004)*.38
        white+=box(u,v,.81,.72,.13,.10,.006)
        white+=box(u,v,.80,.90,.24,.10,.006)*.95
        teal=box(u,v,.78,.47,.014,.50,.012)*.45
        violet=box(u,v,.48,.20,.55,.01,.008)*.48
        # A weak, crisp panel reflected in the flat front pane.
        white+=box(u,v,.58,.59,.32,.012,.004)*.15
        rgb=(white*255+violet*100,white*255+teal*190+violet*35,white*255+teal*175+violet*230)
        row.extend([*(min(255,round(c)) for c in rgb),255])
    rows.append(b'\0'+row)
def chunk(t,b):return struct.pack('>I',len(b))+t+b+struct.pack('>I',zlib.crc32(t+b)&0xffffffff)
png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',size,size,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(b''.join(rows),9))+chunk(b'IEND',b'')
root=Path(__file__).resolve().parents[1]
(root/'Assets/GlossMap.png').write_bytes(png)
(root/'Assets/IplGlossData.g.cs').write_text('// Generated by Tools/generate_gloss_map.py. Original studio-light map.\ninternal static class IplGlossData\n{\n    internal static readonly byte[] Png=new byte[]{'+','.join(map(str,png))+'};\n}\n')
