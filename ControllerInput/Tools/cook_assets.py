CONTROL_POLYGONS['X'] = [(470,136),(478,137),(484,143),(489,153),(492,165),(491,175),(487,181),(480,184),(473,182),(468,177),(467,168),(466,158),(462,148),(463,141)]
CONTROL_POLYGONS['Y'] = [(401,132),(402,125),(408,119),(416,116),(427,113.5),(437,114),(443,117),(447,124),(447,131),(443,137),(435,139),(425,139),(417,142),(411,145),(405,143)]


def make_plate(original: Image.Image, clean: Image.Image) -> tuple[Image.Image, Image.Image]:
    # Build at source resolution, then resample plate and original identically.
    sx, sy = original.width / SIZE[0], original.height / SIZE[1]
    mask = Image.new('L', original.size)
    draw = ImageDraw.Draw(mask)
    def pts(values):
        return [(round(x*sx), round(y*sy)) for x,y in values]
    for polygon in CONTROL_POLYGONS.values():
        draw.polygon(pts(polygon), fill=255)
    for box in CONTROL_ELLIPSES.values():
        draw.ellipse((round(box[0]*sx),round(box[1]*sy),round(box[2]*sx),round(box[3]*sy)), fill=255)
    # One native pixel guard catches the baked dark edge while preserving the
    # surrounding indigo shell. Blur only the subpixel outer seam.
    mask = mask.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(.65))
    ui = ImageDraw.Draw(mask)
    def rectangle(box):
        ui.rectangle((round(box[0]*sx),round(box[1]*sy),round(box[2]*sx),round(box[3]*sy)),fill=255)
    # The source clean plate preserves the exact typography and panel divisions.
    # Port selected fill, port numbers, connection status, numeric fields only.
    for box in ((450,29,485,47),(492,29,526,47),(532,29,566,47),(572,29,606,47),
                (490,51,607,63),(81,393,158,409),(237,393,311,409),
                (367,391,499,416),(520,391,598,408)):
        rectangle(box)
    plate = Image.composite(clean, original, mask)
    # Exact provenance invariant: no unmasked source pixel changes.
    source_pixels = original.tobytes(); plate_pixels = plate.tobytes()
    assert all(source_pixels[i*4:i*4+4] == plate_pixels[i*4:i*4+4]
               for i,m in enumerate(mask.tobytes()) if m == 0)
    return plate.resize(SIZE,Image.Resampling.LANCZOS), mask.resize(SIZE,Image.Resampling.LANCZOS)


def generate_cs(packages: dict[str, bytes], output: Path):
    with output.open('w') as f:
        f.write('// Generated by Tools/cook_assets.py; do not edit.\n')
        f.write('// Approved photographic shell + separate clean control apertures.\n')
        f.write('using Dolphin.Graphics;\n\ninternal static class HybridAssets\n{\n')
        f.write('    // Packed UTF-16 code units hold two native bytes each. These are binary\n')
        f.write('    // literals, not text; the SDK preserves their length and every code unit.\n')
        f.write('    // Small literal chunks avoid a huge Roslyn byte-array initializer.\n')
        f.write('    private static void CopyInto(byte[] target, int offset, string packed)\n    {\n')
        f.write('        for(int i=0;i<packed.Length;i++)\n        {\n')
        f.write('            int value=packed[i];\n')
        f.write('            target[offset++]=(byte)value;\n')
        f.write('            if(offset<target.Length) target[offset++]=(byte)(value>>8);\n')
        f.write('        }\n    }\n')
        for name, data in packages.items():
            f.write(f'    // DNTX v1 RGBA8, 640x480; {len(data):,} bytes including header.\n')
            f.write(f'    internal static Texture2D Load{name}()\n    {{\n')
            f.write('        // Startup-local staging is released after native texture upload.\n')
            f.write(f'        byte[] package = new byte[{len(data)}];\n')
            for offset in range(0,len(data),4096):
                chunk=data[offset:offset+4096]
                if len(chunk)%2: chunk += b'\0'
                packed=''.join('\\u%04x' % (chunk[i] | chunk[i+1]<<8) for i in range(0,len(chunk),2))
                f.write(f'        CopyInto(package, {offset}, "{packed}");\n')
            f.write('        return Texture2D.FromPackage(package, true);\n    }\n')
        f.write('}\n')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tool',default=shutil.which('dnd-assets') or 'dnd-assets')
    args=parser.parse_args()
    original=Image.open(ROOT/'Design/approved-mockup.png').convert('RGBA')
    clean=Image.open(ROOT/'Design/clean-plate-source.png').convert('RGBA')
    assert original.size == clean.size == (1448,1086)
    plate, mask=make_plate(original,clean)
    assets=ROOT/'Assets'; assets.mkdir(exist_ok=True)
    packages={}
    provenance={'size':SIZE,'sdk_assets_version':'0.1.0-preview.361.1','format':'GX RGBA8','sources':{},'packages':{}}
    for source in ('approved-mockup.png','clean-plate-source.png'):
        provenance['sources'][source]=hashlib.sha256((ROOT/'Design'/source).read_bytes()).hexdigest()
    with tempfile.TemporaryDirectory(prefix='controller-assets-') as temporary:
        temporary=Path(temporary)
        for name,im in (('Original',original.resize(SIZE,Image.Resampling.LANCZOS)),('Plate',plate)):
            png=temporary/f'{name}.png'; package=temporary/f'{name}.dndtex'
            im.save(png)
            subprocess.run([args.tool,'texture',str(png),str(package)],check=True)
            packages[name]=package.read_bytes()
            provenance['packages'][name]={'bytes':len(packages[name]),'sha256':hashlib.sha256(packages[name]).hexdigest()}
        generate_cs(packages,assets/'HybridAssets.g.cs')
    plate.save(assets/'plate-preview.png')
    (assets/'provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')
    print('Cooked original + clean plate:', ', '.join(f'{name} {len(data):,} bytes' for name,data in packages.items()))

if __name__=='__main__': main()
