#!/usr/bin/env python3
"""Cook the approved photo plate and inpainted functional cutouts.

This is technical registration/masking only: all artwork is retained from the
approved mockup except the listed moving-control and live-telemetry footprints,
which come from the separately authored clean plate. Run with Pillow and the
published DolphinDotNet.Assets 0.1.0-preview.361.1 dotnet tool available.
"""
